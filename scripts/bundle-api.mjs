import { build } from 'esbuild'
import { mkdir, writeFile } from 'node:fs/promises'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'

const root = join(dirname(fileURLToPath(import.meta.url)), '..')
const apiDir = join(root, 'api')
const entry = join(root, 'server/vercel-entry.ts')

/**
 * Bundle into api/*.ts (not .js).
 * Vercel deploys TS serverless entries for this Vite project but rejects
 * prebundled api/*.js during deploy analysis. Emitting @ts-nocheck ESM into
 * .ts keeps deploy green and avoids runtime MODULE_NOT_FOUND.
 */
await mkdir(apiDir, { recursive: true })

const result = await build({
  absWorkingDir: root,
  entryPoints: [entry],
  bundle: true,
  platform: 'node',
  format: 'esm',
  target: 'node20',
  write: false,
  external: ['pg', 'pg-native'],
  logLevel: 'info',
  plugins: [
    {
      name: 'stub-pglite',
      setup(b) {
        b.onResolve({ filter: /^@electric-sql\/pglite$/ }, () => ({
          path: 'pglite-stub',
          namespace: 'stub',
        }))
        b.onLoad({ filter: /.*/, namespace: 'stub' }, () => ({
          contents: `
            export class PGlite {
              constructor() {
                throw new Error(
                  'PGlite is not bundled for Vercel. Set DATABASE_URL (Neon).',
                )
              }
            }
          `,
          loader: 'js',
        }))
      },
    },
  ],
})

const bundled = result.outputFiles?.[0]?.text
if (!bundled) {
  throw new Error('bundle-api: esbuild produced no output')
}

const source = `// @ts-nocheck
/* eslint-disable */
/* Generated by scripts/bundle-api.mjs — do not edit */
${bundled}`

await writeFile(join(apiDir, 'index.ts'), source)
await writeFile(join(apiDir, '[...path].ts'), source)
console.log(
  'bundle-api: wrote api/index.ts and api/[...path].ts',
  `(${source.length} bytes)`,
)
