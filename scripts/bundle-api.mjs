import { build } from 'esbuild'
import { mkdir, rm, writeFile } from 'node:fs/promises'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'

const root = join(dirname(fileURLToPath(import.meta.url)), '..')
const outDir = join(root, 'server/generated')
const outfile = join(outDir, 'handler.js')

/**
 * Bundle the Hono app outside /api so Vercel does not treat the fat
 * file as a serverless entry (prebundled api/*.js was failing deploy).
 * Thin api/*.ts files re-export from this generated handler.
 */
await mkdir(outDir, { recursive: true })
await rm(outfile, { force: true })

await build({
  absWorkingDir: root,
  entryPoints: [join(root, 'server/vercel-entry.ts')],
  outfile,
  bundle: true,
  platform: 'node',
  format: 'esm',
  target: 'node20',
  external: ['pg', 'pg-native'],
  logLevel: 'info',
  plugins: [
    {
      name: 'stub-pglite',
      setup(b) {
        b.onResolve({ filter: /^@electric-sql\/pglite$/ }, () => ({
          path: 'pglite-stub',
          namespace: 'stub',
        }))
        b.onLoad({ filter: /.*/, namespace: 'stub' }, () => ({
          contents: `
            export class PGlite {
              constructor() {
                throw new Error(
                  'PGlite is not bundled for Vercel. Set DATABASE_URL (Neon).',
                )
              }
            }
          `,
          loader: 'js',
        }))
      },
    },
  ],
})

await writeFile(
  join(outDir, '.gitkeep'),
  'Generated by scripts/bundle-api.mjs during build.\n',
)

console.log('bundle-api: wrote', outfile)
